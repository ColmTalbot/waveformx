"""Write ``src/waveformjax/models/xpnr/_generated/dop853.py``: the
coefficients of the Dormand-Prince 8(5,3) Runge-Kutta method and of its
seventh-order dense output (Hairer, Norsett & Wanner, "Solving Ordinary
Differential Equations I", 2nd ed., Springer 1993), as tabulated by SciPy
(``scipy/integrate/_ivp/dop853_coefficients.py``, BSD-3-Clause; see
NOTICE.md). Only the non-zero coefficients are written.

Usage: ``python scripts/generate_dop853.py`` (needs SciPy).
"""

from pathlib import Path

import numpy as np
from scipy.integrate._ivp import dop853_coefficients as d

OUT = Path(__file__).resolve().parent.parent / "src" / "waveformjax" / "models" / "xpnr" / "_generated" / "dop853.py"

HEADER = '''# SPDX-License-Identifier: GPL-3.0-or-later
# Copyright (C) 2026 Colm Talbot. waveformjax follows LALSuite, GSL and
# waveformrs: see NOTICE.md for the original code and its authors.
#
# GENERATED by scripts/generate_dop853.py from SciPy's
# scipy/integrate/_ivp/dop853_coefficients.py (BSD-3-Clause, see NOTICE.md);
# do not edit.
"""Coefficients of the Dormand-Prince 8(5,3) method and its dense output
(Hairer, Norsett & Wanner 1993). ``A[s]`` lists the non-zero ``(j, a_sj)``
of stage ``s`` (stages 12 to 15 are the extra stages of the dense output),
``B`` the weights of the eighth-order solution and ``D[i]`` the non-zero
``(j, d_ij)`` of the dense-output polynomial coefficients 3 to 6."""

# flake8: noqa
'''


def sparse_rows(matrix):
    return tuple(tuple((j, float(x)) for j, x in enumerate(row) if x != 0.0) for row in matrix)


def main():
    a = sparse_rows(d.A)
    b = tuple((j, float(x)) for j, x in enumerate(d.B) if x != 0.0)
    dd = sparse_rows(d.D)
    lines = [HEADER]
    lines.append(f"N_STAGES = {d.N_STAGES}")
    lines.append(f"N_STAGES_EXTENDED = {d.N_STAGES_EXTENDED}")
    lines.append(f"C = {tuple(float(x) for x in d.C)!r}")
    lines.append(f"A = {a!r}")
    lines.append(f"B = {b!r}")
    lines.append(f"D = {dd!r}")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
