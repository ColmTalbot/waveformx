"""Generate ``src/waveformjax/models/xpnr/_generated/`` from waveformrs.

The parameter-space fits, coefficient tables and closed-form expressions of
IMRPhenomX are translated from the Rust sources of waveformrs by
``scripts/rust_to_python.py``; this script lists which functions go into
which module, adds the imports and the few hand-written replacements, and
writes the modules. Run it from the repository root with the waveformrs
checkout next to it (``../waveformrs``, or ``--waveformrs PATH``)::

    python scripts/generate_fits.py

The generated files are committed; regenerate them only when waveformrs
changes.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import rust_to_python as r2p  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "waveformjax" / "models" / "xpnr" / "_generated"

HEADER = '''# SPDX-License-Identifier: GPL-3.0-or-later
# Copyright (C) 2026 Colm Talbot. waveformjax follows LALSuite, GSL and
# waveformrs: see NOTICE.md for the original code and its authors.
#
# GENERATED by scripts/generate_fits.py from waveformrs {source}
# (itself translated from LALSimulation 6.2.0); do not edit.
"""{doc}"""

# flake8: noqa
import jax.numpy as jnp

from .._math import (DBL_MIN, EGAMMA, FRAC_PI_2, FRAC_PI_4, INF, LN_2, NAN, PI,
                     POWERS_OF_LALPI, fma, fms, fnms, sqrt_nonneg)
'''

# module -> (rust source relative to src/, docstring, functions (None: all),
#            excluded functions, consts (None: all), extra prelude); the
# other parts of the model add theirs in scripts/fits_*.py
MODULES = {
    "inspiral": (
        "imrphenomx/inspiral.rs",
        "Inspiral fits and ansatzes of the (2,2) mode (``LALSimIMRPhenomX_inspiral.c``).",
        None, [], None, "",
    ),
    "intermediate": (
        "imrphenomx/intermediate.rs",
        "Intermediate fits and ansatzes of the (2,2) mode (``LALSimIMRPhenomX_intermediate.c``).",
        None, [], None, "",
    ),
    "ringdown": (
        "imrphenomx/ringdown.rs",
        "Ringdown fits and ansatzes of the (2,2) mode (``LALSimIMRPhenomX_ringdown.c``).",
        None, [], None, "",
    ),
    "utilities": (
        "imrphenomx/utilities.rs",
        "Fits of ``LALSimIMRPhenomXUtilities.c``: characteristic frequencies, final state, time alignment.",
        None, ["f_isco", "assert_exact", "fits_match_lalsimulation"], None,
        '''

def f_isco(chif):
    """``XLALSimIMRPhenomXfISCO``: the ISCO frequency of a Kerr black hole
    of spin ``chif`` (units of its mass)."""
    z1 = fma(jnp.cbrt(fma(-chif, chif, 1.0)), jnp.cbrt(1.0 + chif) + jnp.cbrt(1.0 - chif), 1.0)
    z1 = jnp.minimum(z1, 3.0)
    z2 = jnp.sqrt(fma(3.0 * chif, chif, z1 * z1))
    r_isco = fma(-sign(chif), jnp.sqrt((3.0 - z1) * fma(2.0, z2, 3.0 + z1)), 3.0 + z2)
    r_isco_sq = jnp.sqrt(r_isco)
    r_isco_3o2 = r_isco_sq * r_isco_sq * r_isco_sq
    omega_isco = 1.0 / (r_isco_3o2 + chif)
    return omega_isco / PI
''',
    ),
    "qnm": (
        "imrphenomx/qnm.rs",
        "Quasi-normal-mode fits of the (2,2) mode (``LALSimIMRPhenomX_qnm.c``).",
        None, ["fma_sum"], None,
        '''

def fma_sum(constant, coefficients, powers):
    """``constant + sum_i coefficients[i] powers[i]``, accumulated left to right."""
    total = constant
    for c, x in zip(coefficients, powers):
        total = fma(c, x, total)
    return total
''',
    ),
}


def load_specs():
    """``MODULES`` here and in every ``scripts/fits_*.py`` (one per part of
    the model; each defines a ``MODULES`` dict in the format above)."""
    modules = dict(MODULES)
    for path in sorted(Path(__file__).resolve().parent.glob("fits_*.py")):
        namespace = {}
        exec(compile(path.read_text(), str(path), "exec"), namespace)
        for name, spec in namespace["MODULES"].items():
            if name in modules:
                raise ValueError(f"module {name} is generated twice ({path.name})")
            modules[name] = spec
    return modules


def translate(path: Path, functions, excluded, consts):
    src, items = r2p.parse_file(path)
    emitter = r2p.Emitter()
    out = []
    names = []
    for item in items:
        if isinstance(item, r2p.Function):
            if item.owner is not None and "Self" not in item.params[:1] and item.params[:1] != ["self"]:
                pass
            if functions is not None and item.name not in functions:
                continue
            if item.name in excluded or item.name.startswith("test") or item.owner == "tests":
                continue
            if item.params[:1] == ["self"]:
                continue
            doc = r2p.doc_comment(src, src.find("fn " + item.name + "("))
            out.append(emitter.function(item, docstring=doc.replace('"""', "'''") or None))
            names.append(item.name)
        elif isinstance(item, r2p.Const):
            if consts is not None and item.name not in consts:
                continue
            out.append(f"{item.name} = {emitter.const_value(item.value)}")
    return out, names


def clean(code: str) -> str:
    # sqrt(1 - 4 eta) with a finite derivative at equal masses
    code = code.replace("jnp.sqrt(fma(-4.0, eta, 1.0))", "sqrt_nonneg(fma(-4.0, eta, 1.0))")
    code = code.replace("jnp.sqrt(fnms(4.0, eta, 1.0))", "sqrt_nonneg(fnms(4.0, eta, 1.0))")
    # sqrt(eta (1 - 4 eta)), which also vanishes at equal masses
    code = code.replace("jnp.sqrt(fma(-4.0, eta2, eta))", "sqrt_nonneg(fma(-4.0, eta2, eta))")
    code = re.sub(r"\bcrate\.[a-z_]+\.(?:[a-z_]+\.)*", "", code)
    code = re.sub(r"\bsuper\.(?:[a-z_]+\.)*", "", code)
    return code


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--waveformrs", default=str(ROOT.parent / "waveformrs"))
    parser.add_argument("modules", nargs="*", default=None)
    args = parser.parse_args(argv)
    waveformrs = Path(args.waveformrs)
    if not (waveformrs / "src").is_dir():
        # a git worktree of waveformjax: look next to the main checkout
        for parent in ROOT.parents:
            if (parent / "waveformrs" / "src").is_dir():
                waveformrs = parent / "waveformrs"
                break
    OUT.mkdir(parents=True, exist_ok=True)
    init = OUT / "__init__.py"
    if not init.exists():
        init.write_text(
            HEADER.split("#\n# GENERATED")[0]
            + '"""Modules generated from waveformrs by ``scripts/generate_fits.py``."""\n'
        )
    commit = subprocess.run(
        ["git", "-C", str(waveformrs), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    for module, (source, doc, functions, excluded, consts, prelude) in load_specs().items():
        if args.modules and module not in args.modules:
            continue
        out, names = translate(waveformrs / "src" / source, functions, excluded, consts)
        code = HEADER.format(source=f"src/{source} ({commit})", doc=doc) + prelude + "\n\n" + "\n\n\n".join(out) + "\n"
        code = clean(code)
        path = OUT / f"{module}.py"
        path.write_text(code)
        todo = code.count("NotImplementedError")
        print(f"{path.relative_to(ROOT)}: {len(names)} functions" + (f", {todo} untranslated" if todo else ""))


if __name__ == "__main__":
    main()
