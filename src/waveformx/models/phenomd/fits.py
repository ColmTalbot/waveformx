def _poly(coefficients, x):
    total = 0.0
    for c in reversed(coefficients):
        total = total * x + c
    return total


def final_spin(eta, delta, chi1, chi2):
    """``FinalSpin0815``: the spin of the remnant."""
    x1, x2 = 0.5 * (1.0 + delta), 0.5 * (1.0 - delta)
    s = x1 * x1 * chi1 + x2 * x2 * chi2
    total = 0.0
    for row in reversed(_FINAL_SPIN):
        total = total * s + _poly(row, eta)
    return total


def radiated_energy(eta, delta, chi1, chi2):
    """``EradRational0815``: the energy radiated, in units of the total
    mass."""
    x1, x2 = 0.5 * (1.0 + delta), 0.5 * (1.0 - delta)
    m1s, m2s = x1 * x1, x2 * x2
    s = (m1s * chi1 + m2s * chi2) / (m1s + m2s)
    eta2 = eta * eta
    eta3 = eta2 * eta
    return (eta * (0.055974469826360077 + 0.5809510763115132 * eta - 0.9606726679372312 * eta2
                   + 3.352411249771192 * eta3)
            * (1.0 + (-0.0030302335878845507 - 2.0066110851351073 * eta + 7.7050567802399215 * eta2) * s)) \
        / (1.0 + (-0.6714403054720589 - 1.4756929437702908 * eta + 7.304676214885011 * eta2) * s)


def _chebyshev(coefficients, t):
    """Clenshaw's sum of a Chebyshev series."""
    b1 = b2 = 0.0
    for c in reversed(coefficients[1:]):
        b1, b2 = 2.0 * t * b1 - b2 + c, b1
    return t * b1 - b2 + coefficients[0]


def qnm(final_spin_):
    """``(Mf_ring, Mf_damp)`` of the (2,2) mode in units of the final mass
    for the final spin: the fits of :mod:`._qnm_fit` (LAL interpolates its
    table)."""
    t = 2.0 * jnp.cbrt(0.5 * (1.0 - final_spin_)) - 1.0
    return _chebyshev(_qnm_fit.FRING, t), _chebyshev(_qnm_fit.FDAMP, t)
