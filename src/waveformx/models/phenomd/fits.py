def chi_pn(eta, delta, chi1, chi2):
    """The reduced spin ``chi_PN`` of the fits."""
    chi_s = 0.5 * (chi1 + chi2)
    chi_a = 0.5 * (chi1 - chi2)
    return chi_s * (1.0 - eta * 76.0 / 113.0) + delta * chi_a


def phenomenological(eta, xi, coefficients):
    """``sum_i xi^i sum_j c_ij eta^j`` (``xi = chi_PN - 1``)."""
    total = 0.0
    for row in reversed(coefficients):
        total = total * xi + (row[0] + eta * (row[1] + eta * row[2]))
    return total


